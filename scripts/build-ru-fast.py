def pick_source(k: str) -> tuple[str, str]:
    ev = en.get(k) if False else None  # filled below after HAND
    return "zh-CN", k


def gtx(text: str, sl: str) -> str:
    ck = f"{sl}|{text}"
    if ck in cache:
        return cache[ck]
    url = (
        "https://translate.googleapis.com/translate_a/single"
        f"?client=gtx&sl={sl}&tl=ru&dt=t&q={urllib.parse.quote(text)}"
    )
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    last = None
    for attempt in range(3):
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                data = json.loads(r.read().decode())
            parts = []
            if data and data[0]:
                for seg in data[0]:
                    if seg and seg[0]:
                        parts.append(seg[0])
            out = "".join(parts) if parts else text
            cache[ck] = out
            return out
        except Exception as e:
            last = e
            time.sleep(0.4 * (attempt + 1))
    print("FAIL", repr(text[:40]), last, flush=True)
    return text


def main() -> None:
    keys = list(zh.keys())
    # Prefer EN as MT source when EN is real English
    global en
    en = json.loads((ROOT / "lang" / "en.json").read_text(encoding="utf-8"))

    ru: dict[str, str] = {}
    todo: list[tuple[str, str, str]] = []  # key, sl, src
    for k in keys:
        if k in HAND:
            ru[k] = HAND[k]
            continue
        ev = en.get(k)
        if isinstance(ev, str) and ev and not cjk.search(ev) and ev != k:
            sl, src = "en", ev
        else:
            sl, src = "zh-CN", k
        ck = f"{sl}|{src}"
        if ck in cache:
            ru[k] = cache[ck]
        elif not re.search(r"[A-Za-z\u0400-\u04FF\u4e00-\u9fff]", src):
            ru[k] = src
        else:
            todo.append((k, sl, src))

    print(f"done {len(ru)} hand/cache, todo {len(todo)}", flush=True)
    start = time.time()
    done = 0

    def work(item: tuple[str, str, str]) -> tuple[str, str]:
        k, sl, src = item
        return k, gtx(src, sl)

    with ThreadPoolExecutor(max_workers=WORKERS) as ex:
        futs = [ex.submit(work, item) for item in todo]
        for fut in as_completed(futs):
            k, val = fut.result()
            ru[k] = val
            done += 1
            if done % 30 == 0 or done == len(todo):
                cache_path.write_text(json.dumps(cache, ensure_ascii=False), encoding="utf-8")
                rate = done / max(time.time() - start, 0.1)
                eta = (len(todo) - done) / max(rate, 0.01)
                print(f"{done}/{len(todo)} {rate:.2f}/s eta={eta:.0f}s", flush=True)

    for k, v in list(ru.items()):
        if isinstance(v, str) and "！" in v:
            ru[k] = v.replace("！", "!")

    ordered = {k: ru.get(k, k) for k in keys}
    out_path.write_text(json.dumps(ordered, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    cache_path.write_text(json.dumps(cache, ensure_ascii=False), encoding="utf-8")
    still = sum(1 for v in ordered.values() if cjk.search(str(v)))
    print("wrote", out_path, "keys", len(ordered), "still_cjk", still, "elapsed", round(time.time() - start, 1))
    for k in ("登录", "我的组织", "未找到", "保存", "翻译工作台", "网络错误"):
        print(f"  {k} => {ordered.get(k)}")


if __name__ == "__main__":
    main()
